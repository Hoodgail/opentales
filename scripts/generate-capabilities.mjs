import { readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = path.join(root, 'docs/generated-capabilities.md');

const routeSources = [
  ['Novel Build and scenes', 'packages/backend/src/routes/novelBuildRoutes.ts'],
  ['Publishing', 'packages/backend/src/routes/exportImportRoutes.ts'],
  ['Snapshots and annotations', 'packages/backend/src/routes/revisionRoutes.ts'],
  ['Refactoring', 'packages/backend/src/routes/refactorRoutes.ts']
];

function routeRows(source) {
  return [...source.matchAll(/\.\s*(get|post|patch|delete)\(\s*['"]([^'"]+)['"]/g)]
    .map((match) => `| ${match[1].toUpperCase()} | \`${match[2]}\` |`);
}

async function skillRows() {
  const directory = path.join(root, 'packages/backend/src/useCases/ai/skills');
  const rows = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    try {
      const manifest = JSON.parse(await readFile(path.join(directory, entry.name, 'skill.json'), 'utf8'));
      rows.push(`| \`${manifest.name}\` | \`${manifest.version}\` | \`${manifest.kind}\` | ${manifest.allowedTools?.length ?? 0} |`);
    } catch {
      // The validation suite reports missing/invalid manifests. The generated
      // capability page lists only valid machine-readable contracts.
    }
  }
  return rows.sort();
}

async function render() {
  const sections = [];
  for (const [title, relative] of routeSources) {
    const source = await readFile(path.join(root, relative), 'utf8');
    sections.push(`## ${title}\n\n| Method | Route fragment |\n| --- | --- |\n${routeRows(source).join('\n')}`);
  }
  const skills = await skillRows();
  return `# Generated capabilities\n\n> Generated from Express route declarations and versioned Agent Skill manifests by \`pnpm docs:generate\`. Do not edit this file directly.\n\nRoute fragments are mounted below the authenticated project router; consult the route source for the full prefix.\n\n${sections.join('\n\n')}\n\n## Built-in Agent Skills\n\n| Skill | Version | Kind | Allowed tools |\n| --- | --- | --- | ---: |\n${skills.join('\n')}\n`;
}

const expected = await render();
if (process.argv.includes('--write')) {
  await writeFile(outputPath, expected, 'utf8');
  process.stdout.write(`Updated ${path.relative(root, outputPath)}.\n`);
} else {
  const current = await readFile(outputPath, 'utf8').catch(() => '');
  if (current !== expected) {
    process.stderr.write('Generated capability documentation is stale. Run `pnpm docs:generate`.\n');
    process.exitCode = 1;
  } else {
    process.stdout.write('Generated capability documentation is current.\n');
  }
}
